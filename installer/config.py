"""Patch GRUB configs: the early config embedded in a core image, and menus.

grub-install with GRUB_ENABLE_CRYPTODISK=y embeds lines such as

    cryptomount -u 1234abcd...

which become

    unlock_theme -t "$cmdpath/unlock-theme/theme.txt" -u 1234abcd...

$cmdpath is the directory the EFI image was loaded from, so the theme lives
next to the image on the (unencrypted) ESP.
"""

import re
import shlex

THEME_DIR_NAME = "unlock-theme"
THEME_PATH = "$cmdpath/" + THEME_DIR_NAME + "/theme.txt"

_CRYPTOMOUNT = re.compile(r"^(\s*)cryptomount(?:\s+(.*?))?\s*$")
_UNLOCK_THEME = re.compile(r'^(\s*)unlock_theme\s+-t\s+(?:"[^"]*"|\S+)\s+(.*?)\s*$')


def _patchable(args):
    """Only "-u UUID" and "DEVICE" forms; key files, protectors, -a/-b and
    explicit passwords are left alone."""
    try:
        tokens = shlex.split(args)
    except ValueError:
        return False
    if len(tokens) == 2 and tokens[0] == "-u":
        return True
    return len(tokens) == 1 and not tokens[0].startswith("-")


def patch(config):
    """Returns (new_config, [(old, new)], [skipped lines])."""
    out, changes, skipped = [], [], []
    for line in config.splitlines():
        m = _CRYPTOMOUNT.match(line)
        if m and m.group(2) and _patchable(m.group(2)):
            new = f'{m.group(1)}unlock_theme -t "{THEME_PATH}" {m.group(2)}'
            changes.append((line, new))
            out.append(new)
            continue
        if m:
            skipped.append(line)
        out.append(line)
    return "\n".join(out) + "\n", changes, skipped


def unpatch(config):
    """Reverses patch(). Returns (new_config, [(old, new)])."""
    out, changes = [], []
    for line in config.splitlines():
        m = _UNLOCK_THEME.match(line)
        if m:
            new = f"{m.group(1)}cryptomount {m.group(2)}"
            changes.append((line, new))
            out.append(new)
        else:
            out.append(line)
    return "\n".join(out) + "\n", changes


def is_patched(config):
    return any(_UNLOCK_THEME.match(l) for l in config.splitlines())


def unlock_lines(config):
    return [l.strip() for l in config.splitlines()
            if _CRYPTOMOUNT.match(l) or _UNLOCK_THEME.match(l)]


# Menu setups: the cryptomount lines live in menu entries of a grub.cfg next
# to the image (often generated). Instead of rewriting them, a block near the
# top loads the module from the ESP; with $unlock_theme set, the module's
# cryptomount override shows the themed screen.

MODULE_FILE = "unlock_theme.mod"
MENU_BEGIN = "### BEGIN unlock-theme ###"
MENU_END = "### END unlock-theme ###"
# $config_directory (the grub.cfg's directory) rather than $cmdpath: the same
# image is often also installed as EFI/BOOT/BOOTX64.EFI. Image readers and the
# video driver are separate modules nothing else pulls in.
MENU_BLOCK = f"""{MENU_BEGIN}
# Themed passphrase screen for cryptomount (installed by GRUB_LUKS_splash).
if insmod "$config_directory/{MODULE_FILE}"; then
  insmod efi_gop
  insmod png
  insmod jpeg
  insmod tga
  set unlock_theme="$config_directory/{THEME_DIR_NAME}/theme.txt"
fi
{MENU_END}
"""

_MENU_BLOCK_RE = re.compile(re.escape(MENU_BEGIN) + r".*?" + re.escape(MENU_END) + r"\n?",
                            re.DOTALL)
_HEADER_END = re.compile(r"^### END \S*/00_header ###$", re.MULTILINE)
_TEMPLATES = re.compile(r"generated by grub-mkconfig using templates\s*\n#\s*from (\S+)")


def has_menu_block(text):
    return MENU_BEGIN in text


def add_menu_block(text):
    """Inserts the block after grub-mkconfig's header section, or at the top."""
    if has_menu_block(text):
        return text
    m = _HEADER_END.search(text)
    if m is None:
        return MENU_BLOCK + "\n" + text
    pos = m.end() + 1
    return text[:pos] + "\n" + MENU_BLOCK + text[pos:]


def remove_menu_block(text):
    return _MENU_BLOCK_RE.sub("", text)


def templates_dir(text):
    """The grub.d directory a generated grub.cfg was made from, if stated."""
    m = _TEMPLATES.search(text)
    return m.group(1) if m else None


def menu_template():
    """A grub.d script that emits the block, so regenerating keeps it."""
    return ("#!/bin/sh\n"
            "# Added by GRUB_LUKS_splash (install.py); removed on uninstall.\n"
            "cat <<'EOF'\n" + MENU_BLOCK + "EOF\n")
